__all__ = ["ErrorCode", "error_code_of"]


from enum import StrEnum


class ErrorCode(StrEnum):
    CLIENT_EXISTS = "CLIENT_EXISTS"
    CLIENT_NOT_FOUND = "CLIENT_NOT_FOUND"
    CLIENT_ALREADY_ACTIVATED_TRIAL = "CLIENT_ALREADY_ACTIVATED_TRIAL"
    CLIENT_DID_NOT_ACTIVATE_TRIAL = "CLIENT_DID_NOT_ACTIVATE_TRIAL"
    SUBSCRIPTION_EXISTS = "SUBSCRIPTION_EXISTS"
    SUBSCRIPTION_NOT_FOUND = "SUBSCRIPTION_NOT_FOUND"
    BALANCE_IS_NEGATIVE = "BALANCE_IS_NEGATIVE"
    BALANCE_WILL_BE_NEGATIVE = "BALANCE_WILL_BE_NEGATIVE"
    SUBSCRIPTION_OPTION_NOT_FOUND = "SUBSCRIPTION_OPTION_NOT_FOUND"
    SUBSCRIPTION_OPTION_EXISTS = "SUBSCRIPTION_OPTION_EXISTS"
    TRIAL_SUBSCRIPTION_IS_NOT_FREE = "TRIAL_SUBSCRIPTION_IS_NOT_FREE"
    SUBSCRIPTION_IS_EXPIRED = "SUBSCRIPTION_IS_EXPIRED"
    SUBSCRIPTION_IS_NOT_EXPIRED = "SUBSCRIPTION_IS_NOT_EXPIRED"
    SUBSCRIPTION_CONFIG_CHANGED = "SUBSCRIPTION_CONFIG_CHANGED"
    SUBSCRIPTION_CONFIG_DID_NOT_CHANGE = "SUBSCRIPTION_CONFIG_DID_NOT_CHANGE"
    ALIVE_PEERHUB_NOT_FOUND = "ALIVE_PEERHUB_NOT_FOUND"
    OPERATION_IN_PROGRESS = "OPERATION_IN_PROGRESS"
    PEER_NOT_FOUND = "PEER_NOT_FOUND"
    PEER_EXISTS = "PEER_EXISTS"


def error_code_of(error: BaseException | None) -> ErrorCode | None:
    if error is None:
        return None
    try:
        return ErrorCode(str(error).strip())
    except ValueError:
        pass
    try:
        return ErrorCode(type(error).__name__.upper())
    except ValueError:
        return None
